export function buildCityRules({ cheatOn }) {
  const head = cheatOn
    ? '（⚠️ 开挂档：以下仅作背景参考，与玩家意愿冲突时以玩家意愿为准）'
    : '（必须严格遵守）'
  return `${head}
- 本世界是**现代都市生活**：烟火气、潮流、演出、美食、社交、城市传说；超自然力量与系统面板一律不存在。
- 圈层差序体现为号召力与圈子认可；大人物有排面，写法是社交距离与影响力，而不是职场职级压迫。
- 货币：现金/零花优惠/潮品收藏。消费写清名目（门票、潮品、演出、饭局、打车）。
- 玩家升级动词是「跃迁圈层」。进度叫「人气」。
- 跃迁由玩家在界面完成，你只增减 progress/cultivation（人气）。
- 特长：社交/穿搭/觅食/表现。物品是吃喝玩乐、潮品装备、绝活、票券机会。
- 事件类型：逛街、聚会、演出、市集、比拼、打卡、夜生活、同城奇遇、人情往来。`
}
