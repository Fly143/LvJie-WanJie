export function buildUrbanRules({ cheatOn }) {
  const head = cheatOn
    ? '（⚠️ 开挂档：以下仅作背景参考，与玩家意愿冲突时以玩家意愿为准）'
    : '（必须严格遵守）'
  return `${head}
- 这是**现代都市职场/商战**世界：金钱、合同、舆论、法律、人设、赛道风口；**禁止**修仙、魔法、异能、系统面板等超自然机制。
- 社会段位差距体现为资源与话语权，不是「境界威压」下跪磕头；下属敬畏老板可以，但写法要职场化。
- 货币：现金/理财/资产三级。大额交易写清名目（融资、股权、版权、项目款）。
- **不要写「突破」**：玩家升级动词是「晋升/上位/拿下」。进度叫「声望经验」。
- 晋升由玩家在界面完成，你只增减 progress/cultivation（声望经验）。
- 专业技能：技术/商业/传媒/法务。物品是装备/资产/课程方法论/证件机会，不是丹药法宝。
- 事件类型偏向：接项目、路演、谈判、跳槽、创业、舆情危机、资本局，而不是打怪寻宝。`
}
