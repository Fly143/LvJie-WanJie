let _uiLang = 'zh-CN'

export function setUiLang(id) {
  _uiLang = S[id] ? id : 'zh-CN'
  try {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = _uiLang
    }
  } catch (e) { /* ignore */ }
  return _uiLang
}

export function getUiLang() {
  return _uiLang
}

export function t(key, a, b) {
  const pack = S[_uiLang] || S['zh-CN']
  let s = pack[key]
  if (s == null) s = S['zh-CN'][key]
  if (s == null) return key
  if (a != null) s = s.replace('{a}', String(a))
  if (b != null) s = s.replace('{b}', String(b))
  return s
}

/** 语言名（欢迎页/设置用） */
export function uiLangName(id) {
  return ({ 'zh-CN': '简体中文', 'zh-TW': '繁體中文', 'en': 'English', 'ja': '日本語' })[id] || id
}
